def glyph_bytes(ch):
    art = GLYPHS[ch]
    assert len(art) == H, ch
    out = []
    for row in art:
        assert len(row) == W, (ch, row)
        byte = 0
        for c, pix in enumerate(row):
            if pix == '#':
                byte |= 1 << (7 - c)   # bit 7 = leftmost pixel
            else:
                assert pix == '.', (ch, row)
        out.append(byte)
    return out


def main():
    chars = [chr(c) for c in range(FIRST, LAST + 1)]
    missing = [c for c in chars if c not in GLYPHS]
    extra = [c for c in GLYPHS if c not in chars]
    if missing or extra:
        sys.exit("glyph set mismatch: missing=%r extra=%r" % (missing, extra))

    print("/* font8x8.c -- ReChord clean-room 8x8 bitmap font data.")
    print(" *")
    print(" * Generated by firmware/drivers/tools/gen_font8x8.py from glyph")
    print(" * designs drawn for this project (ASCII art in the script).")
    print(" * Original work, public-domain-style: use, modify, no attribution.")
    print(" * No third-party CFW or font data was copied.")
    print(" *")
    print(" * Encoding:")
    print(" *   - 95 glyphs, ASCII 0x20..0x7E, in code order")
    print(" *   - one glyph = 8 bytes = 8 pixel rows, top row first")
    print(" *   - bit 7 (MSB) is the LEFTMOST pixel of the row")
    print(" *   - shapes are 5x7 drawn in the 8x8 cell (1 col gap, 1 row gap)")
    print(" */")
    print("")
    print('#include "font.h"')
    print("")
    print("const uint8_t font8x8_data[FONT_GLYPH_COUNT][FONT_CELL_H] = {")
    for ch in chars:
        rows = glyph_bytes(ch)
        hexb = ", ".join("0x%02X" % b for b in rows)
        name = ch if ch not in ("\\",) else "\\\\"
        print("    /* 0x%02X '%s' */ {%s}," % (ord(ch), name, hexb))
    print("};")


if __name__ == "__main__":
    main()
